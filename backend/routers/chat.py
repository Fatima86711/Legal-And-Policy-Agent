# ROUTE 3 — PIPELINE TEST
# POST /chat/test
# ══════════════════════════════════════════════════════════════════════════════

@router.post("/test", status_code=status.HTTP_200_OK)
async def test_pipeline(request: ChatRequest):
    """
    Test endpoint that runs the full pipeline but returns extended
    diagnostic information not included in the standard /query response.

    Intended for development and debugging only. In production you would
    restrict this endpoint or remove it entirely.

    Includes everything from /query plus:
        - classification_label : The raw task type returned by the Coordinator
        - retrieval_score_info : Top and average retrieval scores
        - fallback_triggered   : Whether the no-results fallback was used
        - validation_passed    : Whether the response passed all checks
        - warning_count        : Number of validation warnings raised

    Request body:
        {
            "query": "What does habeas corpus mean?"
        }

    Response 200:
        Full ChatResponse fields plus diagnostic fields listed above.
    """
    print(f"\n🧪 POST /chat/test — Diagnostic run")

    start_time = time.perf_counter()

    try:
        coordinator_result = run(query=request.query)
    except Exception as e:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Pipeline test failed: {str(e)}",
        )

    end_time = time.perf_counter()
    processing_time_ms = (end_time - start_time) * 1000

    base_response = build_chat_response(
        coordinator_result=coordinator_result,
        query=request.query,
        processing_time_ms=processing_time_ms,
    )

    # ── Append Diagnostic Fields ──────────────────────────────────────────────
    diagnostic_response = {
        **base_response,
        "classification_label": coordinator_result.get("task_type", "UNKNOWN"),
        "retrieval_score_info": {
            "top_score": coordinator_result.get("top_score", 0.0),
            "avg_score": coordinator_result.get("avg_score", 0.0),
            "chunks_used": coordinator_result.get("chunks_used", 0),
        },
        "fallback_triggered":  coordinator_result.get("used_fallback", False),
        "validation_passed":   coordinator_result.get("is_valid", True),
        "warning_count":       len(coordinator_result.get("warnings", [])),
    }

    return JSONResponse(
        status_code=status.HTTP_200_OK,
        content=diagnostic_response,
    )


