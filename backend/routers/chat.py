# routers/chat.py

import time
from fastapi import APIRouter, HTTPException, status
from fastapi.responses import JSONResponse

from agents.coordinator import run
from models.request_models import ChatRequest
from models.response_models import ChatResponse


# ── Router Initialization ─────────────────────────────────────────────────────
router = APIRouter(
    prefix="/chat",
    tags=["Chat"],
)


# ══════════════════════════════════════════════════════════════════════════════
# HELPER FUNCTIONS
# ══════════════════════════════════════════════════════════════════════════════

def build_chat_response(
    coordinator_result: dict,
    query: str,
    processing_time_ms: float,
) -> dict:
    """
    Build the final structured response dict sent to the frontend.

    Merges the coordinator result with request metadata (original query,
    processing time) into one clean response object that matches the
    ChatResponse Pydantic model.

    Args:
        coordinator_result  : Full result dict from agents/coordinator.run()
        query               : Original user query string
        processing_time_ms  : Total pipeline execution time in milliseconds

    Returns:
        Dict matching the ChatResponse model structure.
    """
    return {
        "query":              query,
        "response":           coordinator_result.get("response", ""),
        "task_type":          coordinator_result.get("task_type", "UNKNOWN"),
        "sources":            coordinator_result.get("sources", []),
        "chunks_used":        coordinator_result.get("chunks_used", 0),
        "top_score":          coordinator_result.get("top_score", 0.0),
        "avg_score":          coordinator_result.get("avg_score", 0.0),
        "used_fallback":      coordinator_result.get("used_fallback", False),
        "is_valid":           coordinator_result.get("is_valid", True),
        "warnings":           coordinator_result.get("warnings", []),
        "error":              coordinator_result.get("error", None),
        "processing_time_ms": round(processing_time_ms, 2),
    }


# ══════════════════════════════════════════════════════════════════════════════
# ROUTE 1 — SEND CHAT MESSAGE
# POST /chat/query
# ══════════════════════════════════════════════════════════════════════════════

@router.post(
    "/query",
    response_model=ChatResponse,
    status_code=status.HTTP_200_OK,
)
async def chat_query(request: ChatRequest):
    """
    Main chat endpoint. Accepts a user query and returns a legal analysis
    response generated by the full multi-agent pipeline.

    The request body is validated by the ChatRequest Pydantic model before
    this function runs. If validation fails, FastAPI returns a 422 automatically.

    Pipeline:
        1. Record start time
        2. Pass query to Coordinator Agent (classify → retrieve → explain)
        3. Record end time and compute processing duration
        4. Build and return structured response

    Request body:
        {
            "query": "What are the GDPR penalties for data breaches?"
        }

    Response 200:
        {
            "query"              : "What are the GDPR penalties...",
            "response"           : "**Legal Analysis**\n\n...",
            "task_type"          : "RETRIEVAL",
            "sources"            : ["gdpr.pdf"],
            "chunks_used"        : 5,
            "top_score"          : 0.87,
            "avg_score"          : 0.74,
            "used_fallback"      : false,
            "is_valid"           : true,
            "warnings"           : [],
            "error"              : null,
            "processing_time_ms" : 2340.5
        }

    Response 422:
        Automatic FastAPI validation error if request body is malformed.

    Response 500:
        { "detail": "Unexpected server error: <message>" }
    """
    print(f"\n{'▶' * 60}")
    print(f"  POST /chat/query")
    print(f"  Query: {request.query[:100]}{'...' if len(request.query) > 100 else ''}")
    print(f"{'▶' * 60}")

    # ── Step 1 — Start Timer ──────────────────────────────────────────────────
    start_time = time.perf_counter()

    # ── Step 2 — Run Coordinator Pipeline ────────────────────────────────────
    try:
        coordinator_result = run(query=request.query)
    except Exception as e:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Unexpected server error: {str(e)}",
        )

    # ── Step 3 — Compute Processing Time ─────────────────────────────────────
    end_time = time.perf_counter()
    processing_time_ms = (end_time - start_time) * 1000

    print(f"⏱️  Processing time: {processing_time_ms:.2f}ms")

    # ── Step 4 — Build and Return Response ───────────────────────────────────
    response_data = build_chat_response(
        coordinator_result=coordinator_result,
        query=request.query,
        processing_time_ms=processing_time_ms,
    )

    return JSONResponse(
        status_code=status.HTTP_200_OK,
        content=response_data,
    )


