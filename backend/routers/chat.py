# ROUTE 4 — CLASSIFY ONLY (No Retrieval, No LLM Generation)
# POST /chat/classify
# ══════════════════════════════════════════════════════════════════════════════

@router.post("/classify", status_code=status.HTTP_200_OK)
async def classify_only(request: ChatRequest):
    """
    Classify a query without running the full pipeline.

    Calls only the Coordinator's classification step — no retrieval,
    no LLM generation beyond the routing call. Returns the task type
    label and the processing time for the classification alone.

    Useful for:
        - Frontend to show the user what type of task their query triggered
          before the full response arrives (e.g. a badge showing "RETRIEVAL")
        - Testing and validating the routing prompt in isolation
        - Debugging misclassification issues during development

    Request body:
        {
            "query": "Compare GDPR with Pakistan's PDPA"
        }

    Response 200:
        {
            "query"              : "Compare GDPR with Pakistan's PDPA",
            "task_type"          : "COMPARISON",
            "processing_time_ms" : 340.2
        }
    """
    from agents.coordinator import classify

    print(f"\n🏷️  POST /chat/classify — Classification only")

    start_time = time.perf_counter()

    try:
        task_type = classify(query=request.query)
    except Exception as e:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Classification failed: {str(e)}",
        )

    end_time = time.perf_counter()
    processing_time_ms = (end_time - start_time) * 1000

    return {
        "query":              request.query,
        "task_type":          task_type,
        "processing_time_ms": round(processing_time_ms, 2),
    }